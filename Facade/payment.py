class Payment:
    def process_payment(self, amount: float) -> None:
        print(f"[To'lov] {amount} so'm miqdorida to'lov muvaffaqiyatli amalga oshirildi.")

    def refund_payment(self, amount: float) -> None:
        print(f"[To'lov] {amount} so'm miqdoridagi mablag' mijoz hisobiga qaytarildi.")
